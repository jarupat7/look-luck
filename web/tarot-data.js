// Helper Functions for Tarot Divination
const TarotEngine = {
  // สุ่มไพ่ 1 ใบ พร้อมคำนวณสถานะหัวตั้ง / กลับหัว
  drawCard: function() {
    const randomIndex = Math.floor(Math.random() * TAROT_CARDS.length);
    const card = TAROT_CARDS[randomIndex];
    // สุ่มทิศทางไพ่: หัวตั้ง 70%, กลับหัว 30% (เพื่อให้พลังงานโดยรวมเป็นกำลังใจแก่ผู้ใช้)
    const isReversed = Math.random() < 0.30;
    
    return {
      card: card,
      isReversed: isReversed,
      orientationText: isReversed ? "ไพ่กลับหัว (Reversed)" : "ไพ่หัวตั้ง (Upright)",
      data: isReversed ? card.reversed : card.upright
    };
  },

  // ดึงไพ่ประจำวันของ User (ล็อคตามวันปัจจุบัน หากต้องการให้ได้ผลเดิมในวันเดียวกัน)
  getDailySeedCard: function(userEmail, dateStr) {
    if (!userEmail) userEmail = "guest";
    if (!dateStr) dateStr = new Date().toISOString().slice(0, 10);
    
    // Hash function ง่ายๆ สำหรับสร้าง seed
    let hash = 0;
    const str = `${userEmail}_${dateStr}`;
    for (let i = 0; i < str.length; i++) {
      hash = ((hash << 5) - hash) + str.charCodeAt(i);
      hash |= 0;
    }
    const positiveHash = Math.abs(hash);
    const cardIndex = positiveHash % TAROT_CARDS.length;
    const isReversed = (positiveHash % 10) < 3; // 30% โอกาสกลับหัว
    
    const card = TAROT_CARDS[cardIndex];
    return {
      card: card,
      isReversed: isReversed,
      orientationText: isReversed ? "ไพ่กลับหัว (Reversed)" : "ไพ่หัวตั้ง (Upright)",
      data: isReversed ? card.reversed : card.upright
    };
  }
};
