/**
 * ฟังก์ชันสุ่มและจัดการผลเซียมซี + ไม้ปวย
 */
const SiamsiEngine = {
  getCardById(id) {
    return SIAMSI_WAT_MANGKON.find(c => c.id === id) || SIAMSI_WAT_MANGKON[0];
  },

  drawStick() {
    // สุ่มไม้ติ้ว 1 ถึง 28
    const randIndex = Math.floor(Math.random() * SIAMSI_WAT_MANGKON.length);
    return SIAMSI_WAT_MANGKON[randIndex];
  },

  tossPuai() {
    // ไม้ปวย 2 ชิ้น แต่ละชิ้นมีหน้า นูน(หยิน=คว่ำ) หรือ แบน(หยาง=หงาย)
    // 0 = นูน(คว่ำ), 1 = แบน(หงาย)
    const p1 = Math.random() < 0.5 ? 'yin' : 'yang';
    const p2 = Math.random() < 0.5 ? 'yin' : 'yang';

    let result = '';
    let title = '';
    let desc = '';
    let approved = false;

    if ((p1 === 'yin' && p2 === 'yang') || (p1 === 'yang' && p2 === 'yin')) {
      // คว่ำ 1 หงาย 1: เซ้งปวย (อนุมัติ)
      result = 'sheng';
      title = '✨ เซ้งปวย (อนุมัติ — 圣杯)';
      desc = 'เทพเจ้าประทานความเห็นชอบ! หมายเลขนี้เป็นคำทำนายที่แท้จริงสำหรับท่าน';
      approved = true;
    } else if (p1 === 'yin' && p2 === 'yin') {
      // คว่ำทั้งคู่: อิมปวย (ไม่อนุมัติ)
      result = 'yin';
      title = '⚡ อิมปวย (ไม่อนุมัติ — 阴杯)';
      desc = 'สิ่งศักดิ์สิทธิ์ปฏิเสธ ใบนี้ยังมิใช่ของท่าน โปรดตั้งจิตอธิษฐานแล้วเขย่ากระบอกติ้วใหม่';
      approved = false;
    } else {
      // หงายทั้งคู่: เอี๊ยงปวย (แย้มสรวล / คลุมเครือ)
      result = 'xiao';
      title = '😊 เอี๊ยงปวย (แย้มสรวล — 笑杯)';
      desc = 'เทพเจ้าแย้มสรวล คำถามยังไม่ชัดเจนหรือยังไม่ถึงเวลา โปรดตั้งสมาธิอธิษฐานใหม่แล้วโยนไม้ปวยอีกครั้ง';
      approved = false;
    }

    return {
      p1,
      p2,
      result,
      title,
      desc,
      approved
    };
  }
};

